"""
Detector experiments (item J): try candidate detector settings one at a
time and measure each with

  (a) frame-level fly count on the test videos (eval_video_counts.py),
      with the count model retrained on the annotated images using that
      detector (the contours change, so the old tree does not apply);
  (b) leave-one-session-out cross-validation of all four tasks
      (the scoring functions of evaluate.py).

Only settings from the original Stanford repo are tried (arena mask,
fixed core threshold 115, mean-5 "wings" threshold), plus switching the
border filter off. No threshold value is tuned on the videos.

Outputs results/metrics/detector_experiments.md and .csv.

Run from the repository root:  python eval_detectors.py
"""

import warnings

from pathlib import Path

import numpy as np
import pandas as pd

import evaluate
import eval_video_counts
import train.train_fly_count as fly_count
import train.train_orientation as orientation
import train.train_sex as sex
import train.train_wing_angle as wing

from src.detection import DETECTOR, set_detector


OUTPUT_MD = Path("results/metrics/detector_experiments.md")
OUTPUT_CSV = Path("results/metrics/detector_experiments.csv")

BASELINE = {"arena_mask": False, "threshold": "otsu", "border_filter": True}

# Tried in this order; each step changes one switch.
CANDIDATES = [
    ("0 baseline (Otsu)", dict(BASELINE)),
    ("1 + arena mask", {**BASELINE, "arena_mask": True}),
    ("2a mask + core threshold 115", {**BASELINE, "arena_mask": True, "threshold": "core"}),
    ("2b mask + wings threshold (mean - 5)", {**BASELINE, "arena_mask": True, "threshold": "wings"}),
    ("3a mask + core 115, no border filter",
     {"arena_mask": True, "threshold": "core", "border_filter": False}),
    ("3b mask + Otsu, no border filter",
     {"arena_mask": True, "threshold": "otsu", "border_filter": False}),
]


def mean_of(folds, metric):

    values = [fold[metric] for fold in folds if metric in fold]

    return np.mean(values) if values else np.nan


def run_candidate(name, settings):

    set_detector(**settings)

    print(f"\n=== {name}: {DETECTOR}")

    data = {
        "count": fly_count.build_dataset(),
        "sex": sex.build_dataset(),
        "orientation": orientation.build_dataset(),
        "wing": wing.build_dataset()
    }

    # (a) videos, with a count tree trained on all annotated contours
    count_model = fly_count.make_model()
    count_model.fit(data["count"]["X"], data["count"]["y"])

    summary, _ = eval_video_counts.evaluate_videos(count_model)

    per_video = dict(zip(summary["video"], summary["count_eq_2_pct"]))

    total = np.sum(summary["count_eq_2_pct"] * summary["decoded_frames"]) / summary["decoded_frames"].sum()

    # (b) leave-one-session-out cross-validation
    count_folds = evaluate.score_fly_count(data["count"], "session")
    sex_folds = evaluate.score_sex(data["sex"], "session")
    orient_folds = evaluate.score_orientation(data["orientation"], "session")
    wing_folds = evaluate.score_wing(data["wing"], data["orientation"], "session")

    row = {
        "candidate": name,
        "settings": str(settings),
        "video count==2, all (%)": total,
        **{f"{video} (%)": value for video, value in per_video.items()},
        "count contours": len(data["count"]["y"]),
        "count images with contour": len(np.unique(data["count"]["image"])),
        "LOSO contour acc (%)": mean_of(count_folds, "contour accuracy (%)"),
        "LOSO image count acc (%)": mean_of(count_folds, "image count accuracy (%)"),
        "sex flies": len(data["sex"]["y"]),
        "LOSO sex acc (%)": mean_of(sex_folds, "accuracy (%)"),
        "orientation flies": len(data["orientation"]["y"]),
        "LOSO flip error (%)": mean_of(orient_folds, "flip error (%)"),
        "LOSO angle error (deg)": mean_of(orient_folds, "angular error, mean (deg)"),
        "LOSO axis-only error (deg)": mean_of(orient_folds, "axis-only error, perfect flip (deg)"),
        "wing males": len(data["wing"]["image"]),
        "LOSO wing MAE true orient (deg)": mean_of(wing_folds, "MAE linear, true orientation (deg)"),
        "LOSO wing MAE pred orient (deg)": mean_of(wing_folds, "MAE linear, predicted orientation (deg)"),
        "count tree": ", ".join(
            f"{t:.0f}" for t in sorted(
                count_model.tree_.threshold[count_model.tree_.feature >= 0]
            )
        )
    }

    for key, value in row.items():
        if isinstance(value, float):
            print(f"  {key}: {value:.1f}")

    return row


def write_report(table):

    columns = [column for column in table.columns if column not in ("settings",)]

    lines = [
        "# Detector experiments (item J)",
        "",
        "Generated by `python eval_detectors.py`. Each candidate changes one "
        "detector switch (see `src/detection.py`). For every candidate the "
        "count tree is retrained on the annotated images with that detector, "
        "then run on all test videos (correct count = 2 in every frame), and "
        "all four tasks are scored with leave-one-session-out (LOSO) "
        "cross-validation. Dataset sizes change because the detector decides "
        "which flies are found as separate contours.",
        "",
        "Note: test1 and test4 are not held out (annotated sessions were cut "
        "from them).",
        ""
    ]

    transposed = table.set_index("candidate")[columns[1:]].T

    lines.append("| Metric | " + " | ".join(transposed.columns) + " |")
    lines.append("|---" * (len(transposed.columns) + 1) + "|")

    for metric, values in transposed.iterrows():

        cells = [
            f"{value:.1f}" if isinstance(value, float) else str(value)
            for value in values
        ]

        lines.append(f"| {metric} | " + " | ".join(cells) + " |")

    OUTPUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():

    warnings.filterwarnings("ignore")

    original = dict(DETECTOR)

    rows = [run_candidate(name, settings) for name, settings in CANDIDATES]

    set_detector(**original)

    table = pd.DataFrame(rows)

    table.to_csv(OUTPUT_CSV, index=False, float_format="%.2f")

    write_report(table)

    print("\nWritten:", OUTPUT_MD)


if __name__ == "__main__":
    main()
