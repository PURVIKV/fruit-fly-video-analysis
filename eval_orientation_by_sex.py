"""
Orientation error per sex (item K), leave-one-session-out, for the
original Otsu detector (axis from the full silhouette: legs and wings
included) and the current detector (axis from the dark body core).

Outputs results/metrics/orientation_by_sex.md.

Run from the repository root:  python eval_orientation_by_sex.py
"""

import warnings

from pathlib import Path

import numpy as np

import evaluate
import train.train_orientation as orientation
import train.train_wing_angle as wing

from src.detection import DETECTOR, set_detector


OUTPUT = Path("results/metrics/orientation_by_sex.md")

DETECTORS = [
    ("Before: Otsu silhouette", {"arena_mask": False, "threshold": "otsu", "border_filter": True}),
    ("After: arena mask + core 115", {"arena_mask": True, "threshold": "core", "border_filter": True}),
]

METRICS = [
    "male axis-only error (deg)",
    "female axis-only error (deg)",
    "male angular error (deg)",
    "female angular error (deg)",
    "male flip error (%)",
    "female flip error (%)",
    "flip error (%)",
]


def mean_std(folds, metric):

    values = np.array([fold[metric] for fold in folds if metric in fold])

    return f"{values.mean():.1f} ± {values.std():.1f} (n={len(values)})"


def main():

    warnings.filterwarnings("ignore")

    original = dict(DETECTOR)

    columns = {}

    for name, settings in DETECTORS:

        set_detector(**settings)

        orient_data = orientation.build_dataset()
        wing_data = wing.build_dataset()

        folds = evaluate.score_orientation(orient_data, "session")
        wing_folds = evaluate.score_wing(wing_data, orient_data, "session")

        columns[name] = {metric: mean_std(folds, metric) for metric in METRICS}
        columns[name]["flies (male / female)"] = (
            f"{np.sum(orient_data['sex'] == 'male')} / "
            f"{np.sum(orient_data['sex'] == 'female')}"
        )
        columns[name]["wing MAE, predicted orientation (deg)"] = mean_std(
            wing_folds, "MAE linear, predicted orientation (deg)"
        )
        columns[name]["wing MAE, true orientation (deg)"] = mean_std(
            wing_folds, "MAE linear, true orientation (deg)"
        )

    set_detector(**original)

    names = list(columns)

    lines = [
        "# Orientation error by sex (item K)",
        "",
        "Generated by `python eval_orientation_by_sex.py`. Leave-one-session-out, "
        "mean ± std over sessions (n = number of session folds with flies of "
        "that sex). Axis-only error = moment axis with a perfect head/tail "
        "flip; angular error = final predicted heading.",
        "",
        "| Metric | " + " | ".join(names) + " |",
        "|---" * (len(names) + 1) + "|"
    ]

    for metric in columns[names[0]]:
        lines.append(
            f"| {metric} | " + " | ".join(columns[n][metric] for n in names) + " |"
        )

    lines += [
        "",
        "Note: the two detectors find different sets of isolated flies "
        "(the core detector separates many more), so the populations differ.",
        ""
    ]

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")

    print(OUTPUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
